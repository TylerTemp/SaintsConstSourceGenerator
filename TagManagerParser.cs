        #region RenderingLayers
        private static void WriteRenderingLayers(TagManager tagManager, GeneratorExecutionContext context)
        {
            if (tagManager.m_RenderingLayers == null || tagManager.m_RenderingLayers.Length == 0)
            {
                return;
            }

            HashSet<string> conflictedSet = new HashSet<string>();
            HashSet<string> existsName = new HashSet<string>();
            StringBuilder renderingLayersNameFieldsBuilder = new StringBuilder();
            StringBuilder renderingLayersMaskFieldsBuilder = new StringBuilder();

            for (int index = 0; index < tagManager.m_RenderingLayers.Length; index++)
            {
                string renderingLayer = tagManager.m_RenderingLayers[index];
                if (!string.IsNullOrEmpty(renderingLayer) && renderingLayer.Length != 0)
                {
                    string key = Utils.ProperVarName(renderingLayer);
                    bool conflicted = !existsName.Add(key);
                    if (conflicted)
                    {
                        // Utils.DebugToFile(
                        //     $"RenderingLayer `{renderingLayer}` has conflict programming name `{key}`, skip");
                        conflictedSet.Add(renderingLayer);
                    }
                    else
                    {
                        int mask = 1 << index;
                        renderingLayersNameFieldsBuilder.Append(string.Format(
                            RenderingLayerNameFieldTemplate,
                            key,
                            renderingLayer,
                            mask));
                        renderingLayersMaskFieldsBuilder.Append(string.Format(
                            RenderingLayerMaskFieldTemplate,
                            key,
                            index,
                            renderingLayer,
                            mask));
                    }
                }
            }

            string conflictLine = "";
            // Utils.DebugToFile($"processing conflictLine");
            if (conflictedSet.Count > 0)
            {
                // Utils.DebugToFile($"conflictedSet.Count={conflictedSet.Count}");
                conflictLine = "\n    /// <summary>\n" +
                               $"    /// WARNING: conflict layer mask name found: {string.Join(", ", conflictedSet)}\n" +
                                "    /// </summary>";
            }
            // Utils.DebugToFile($"conflictLine={conflictLine}");

            string fileContent = string.Format(RenderingLayerConstTemplate, conflictLine, renderingLayersNameFieldsBuilder, renderingLayersMaskFieldsBuilder);
            // Utils.DebugToFile($"content={fileContent}");

            context.AddSource("RenderingLayerConst.generated.cs",
                SourceText.From(fileContent, Encoding.UTF8));
        }

