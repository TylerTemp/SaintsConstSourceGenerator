        #region Tags
        private static void WriteTags(TagManager tagManager, GeneratorExecutionContext context)
        {
            Utils.DebugToFile($"found tags {string.Join(", ", tagManager.tags)}");
            HashSet<string> conflictedSet = new HashSet<string>();
            HashSet<string> existsName = new HashSet<string>();
            StringBuilder tagFieldsBuilder = new StringBuilder();

            List<string> tagsWithDefault = new List<string>
            {
                "Respawn",
                "Finish",
                "EditorOnly",
                "MainCamera",
                "Player",
                "GameController",
            };
            tagsWithDefault.AddRange(tagManager.tags);

            foreach (string tag in tagsWithDefault)
            {
                if (!string.IsNullOrEmpty(tag) && tag.Length != 0)
                {
                    string key = Utils.ProperVarName(tag);
                    bool conflicted = !existsName.Add(key);
                    if(conflicted)
                    {
                        Utils.DebugToFile($"Tag `{tag}` has conflict programming name `{key}`, skip");
                        conflictedSet.Add(tag);
                    }
                    else
                    {
                        tagFieldsBuilder.Append(string.Format(
                            TagFieldTemplate,
                            key,
                            tag,
                            tag == key
                                ? ""
                                : string.Format(TagFieldCommentTemplate, tag)));
                    }
                }
            }

            string conflictLine = "";
            // Utils.DebugToFile($"processing conflictLine");
            if (conflictedSet.Count > 0)
            {
                // Utils.DebugToFile($"conflictedSet.Count={conflictedSet.Count}");
                conflictLine = "\n    /// <summary>\n" +
                               $"    /// WARNING: conflict layer mask name found: {string.Join(", ", conflictedSet)}\n" +
                                "    /// </summary>";
            }
            // Utils.DebugToFile($"conflictLine={conflictLine}");

            string fileContent = string.Format(TagConstTemplate, conflictLine, tagFieldsBuilder);
            // Utils.DebugToFile($"content={fileContent}");

            context.AddSource("TagConst.generated.cs",
                SourceText.From(fileContent, Encoding.UTF8));
        }

