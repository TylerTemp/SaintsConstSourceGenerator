        #region SortingLayers

        private static void WriteSortingLayers(TagManager tagManager, GeneratorExecutionContext context)
        {
            if (tagManager.m_SortingLayers == null || tagManager.m_SortingLayers.Length == 0)
            {
                return;
            }

            StringBuilder nameFieldsBuilder = new StringBuilder();
            StringBuilder idFieldsBuilder = new StringBuilder();

            HashSet<string> conflictedSet = new HashSet<string>();

            HashSet<string> existsName = new HashSet<string>();
            for (int index = 0; index < tagManager.m_SortingLayers.Length; index++)
            {
                MSortingLayers sortingLayer = tagManager.m_SortingLayers[index];
                long rawId = sortingLayer.uniqueID;
                int id = rawId > int.MaxValue
                    ? (int) (rawId - 1L << 32)
                    : (int) rawId;
                string key = Utils.ProperVarName(sortingLayer.name);
                bool conflicted = !existsName.Add(key);
                if(conflicted)
                {
                    // Utils.DebugToFile($"SortingLayer `{sortingLayer}` has conflict programming name `{key}`, skip");
                    conflictedSet.Add(sortingLayer.name);
                }
                else
                {
                    nameFieldsBuilder.Append(string.Format(
                        SortingLayerNameTemplate,
                        key,
                        sortingLayer.name,
                        key == sortingLayer.name
                            ? ""
                            : string.Format(SortingLayerNameCommentTemplate, sortingLayer.name)));
                    idFieldsBuilder.Append(string.Format(
                        SortingLayerIdTemplate,
                        key,
                        id,
                        sortingLayer.name));
                }
            }

            string conflictLine = "";
            // Utils.DebugToFile($"processing conflictLine");
            if (conflictedSet.Count > 0)
            {
                // Utils.DebugToFile($"conflictedSet.Count={conflictedSet.Count}");
                conflictLine = "\n    /// <summary>\n" +
                               $"    /// WARNING: conflict layer mask name found: {string.Join(", ", conflictedSet)}\n" +
                                "    /// </summary>";
            }
            // Utils.DebugToFile($"conflictLine={conflictLine}");

            string fileContent = string.Format(SortingLayerConstTemplate, conflictLine, nameFieldsBuilder, idFieldsBuilder);
            // Utils.DebugToFile($"content={fileContent}");

            context.AddSource("SortingLayerConst.generated.cs",
                SourceText.From(fileContent, Encoding.UTF8));
        }

